let page = null
let y = 0
let pageNo = 0

function newPage() {
  page = pres.addSlide()
  page.background = { color: 'FFFFFF' }
  pageNo += 1
  if (pageNo === 1) {
    page.addText('أثر', ar({
      fontFace: DISP, x: M, y: 0.45, w: CW, h: 0.62, fontSize: 26, bold: true, color: TERRA,
    }))
    page.addText('محتوى القالب الموحّد', ar({
      x: M, y: 1.08, w: CW, h: 0.4, fontSize: 18, bold: true, color: INK,
    }))
    page.addText('نصّ كلّ قسم من أقسام قالب هاكاثون AJA AI، جاهزًا للنقل إلى شريحته.', ar({
      x: M, y: 1.5, w: CW, h: 0.3, fontSize: 11, color: MUTED,
    }))
    y = 2.0
  } else {
    y = 0.6
  }
}

newPage()

SECTIONS.forEach(([title, bullets]) => {
  // تقديرُ الارتفاع قبل الرسم: سطرٌ لكلّ ١٠٥ أحرف تقريبًا عند قياس ١٠
  const lines = bullets.reduce((a, b) => a + Math.max(1, Math.ceil(b.length / 105)), 0)
  const h = 0.42 + lines * 0.235 + bullets.length * 0.07 + 0.14
  if (y + h > H - 0.7) newPage()

  page.addShape(pres.ShapeType.roundRect, {
    x: M, y, w: CW, h, rectRadius: 0.06,
    fill: { color: TINT }, line: { color: RULE, width: 0.75 },
  })
  page.addText(title, ar({
    x: M + 0.22, y: y + 0.14, w: CW - 0.44, h: 0.3, fontSize: 13, bold: true, color: TERRA,
  }))
  page.addShape(pres.ShapeType.rect, {
    x: M + 0.22, y: y + 0.46, w: CW - 0.44, h: 0.012,
    fill: { color: RULE }, line: { width: 0 },
  })
  page.addText(
    bullets.map((t, i) => ({
      text: bullet(t),
      options: { breakLine: i < bullets.length - 1, paraSpaceAfter: 5 },
    })),
    ar({
      x: M + 0.22, y: y + 0.58, w: CW - 0.44, h: h - 0.74,
      fontSize: 10, color: MUTED, lineSpacing: 16.5, valign: 'top',
    }),
  )
  y += h + 0.22
})

