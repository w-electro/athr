let s = null
let y = 0

function newPage(first) {
  s = pres.addSlide()
  s.background = { color: 'FFFFFF' }
  if (first) {
    s.addText('أثر', ar({ fontFace: DISP, x: M, y: 0.45, w: CW, h: 0.62, fontSize: 26, bold: true, color: TERRA }))
    s.addText('أسئلة التحكيم وأجوبتها', ar({ x: M, y: 1.08, w: CW, h: 0.4, fontSize: 18, bold: true, color: INK }))
    s.addText('ما قد يسأله المحكمون بعد العرض، مرتبا بمعايير التحكيم، وجواب كل سؤال في جملة أو جملتين.', ar({
      x: M, y: 1.5, w: CW, h: 0.3, fontSize: 11, color: MUTED,
    }))
    y = 2.05
  } else {
    y = 0.6
  }
}

// تقدير الارتفاع: سطرٌ لكلّ 92 حرفًا تقريبًا عند قياس 11
const linesOf = (t, per) => Math.max(1, Math.ceil(t.length / per))

newPage(true)
SECTIONS.forEach(([title, qas]) => {
  if (y + 1.2 > H - 0.7) newPage(false)
  s.addText(title, ar({ x: M, y, w: CW, h: 0.34, fontSize: 14, bold: true, color: TERRA }))
  s.addShape(pres.ShapeType.rect, { x: M, y: y + 0.4, w: CW, h: 0.014, fill: { color: RULE }, line: { width: 0 } })
  y += 0.55

  qas.forEach(([q, a]) => {
    const ah = linesOf(a, 92) * 0.24
    const h = 0.3 + ah + 0.28
    if (y + h > H - 0.6) newPage(false)
    s.addShape(pres.ShapeType.roundRect, {
      x: M, y, w: CW, h, rectRadius: 0.05, fill: { color: TINT }, line: { color: RULE, width: 0.5 },
    })
    s.addText(q, ar({ x: M + 0.2, y: y + 0.12, w: CW - 0.4, h: 0.28, fontSize: 12, bold: true, color: INK }))
    s.addText(a, ar({
      x: M + 0.2, y: y + 0.44, w: CW - 0.4, h: ah, fontSize: 11, color: MUTED, lineSpacing: 17, valign: 'top',
    }))
    y += h + 0.16
  })
  y += 0.2
})

const out = process.argv[2] || path.join(REPO, 'athr-qa-ar.pptx')
pres.writeFile({ fileName: out }).then(() => console.log('qa written:', out))
