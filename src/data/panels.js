/**
 * يدمج النصّ المترجم فوق البنية المشتركة.
 *
 * ── ولماذا يُرجع null بدل العربية ─────────────────────────────────────
 * sites.js يتراجع إلى العربية حين تنقص ترجمة، لأن كل المواقع مترجمة
 * فعلًا فالتراجع نظريّ. أمّا اللوحات فجديدة، ولم تُترجم بعد. وعرضُ قصّة
 * عربية داخل واجهة يابانية عطبٌ مرئيّ، بينما إخفاء اللوحة يُعيد الشاشة
 * إلى سلوكها السابق تمامًا: تعرّفٌ على مستوى الموقع.
 *
 * فالميزة تُفتح لغةً بلغة كلّما وصلت ترجمتها — إضافةٌ خالصة لا كسر.
 */
function localize(panel, language) {
  if (language === 'ar') return panel

  const overlay = getLoadedPanels(language)?.[panel.id]
  return overlay ? { ...panel, ...overlay } : null
}

/** كل اللوحات المتاحة بهذه اللغة. قد تكون فارغة قبل وصول الترجمة. */
export function getAllPanels(language = 'ar') {
  return PANELS.map((panel) => localize(panel, language)).filter(Boolean)
}

/** لوحة واحدة بالمعرّف، أو undefined إن لم تتوفّر بهذه اللغة. */
export function getPanelById(id, language = 'ar') {
  const panel = PANELS.find((entry) => entry.id === id)
  return panel ? (localize(panel, language) ?? undefined) : undefined
}

/** هل تُعرض اللوحات بهذه اللغة أصلًا؟ */
export function hasPanelContent(language = 'ar') {
  return getAllPanels(language).length > 0
}

/** لوحات موقعٍ بعينه. */
export function getPanelsForSite(siteId, language = 'ar') {
  return getAllPanels(language).filter((panel) => panel.siteId === siteId)
}

/**
 * هل هذا المعرّف لوحةً لا موقعًا؟
 *
 * فهرس التعرّف يخلط الاثنين، والواجهة تحتاج أن تفرّق: اللوحة تفتح صفحة
 * لوحة، والموقع يفتح صفحة موقع.
 */
export function isPanelId(id) {
  return typeof id === 'string' && /-p\d+$/.test(id)
}

/** الموقع الذي تنتمي إليه اللوحة، مستخرجًا من معرّفها. */
export function siteIdOfPanel(panelId) {
  return isPanelId(panelId) ? panelId.replace(/-p\d+$/, '') : null
}
