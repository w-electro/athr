/**
 * الكتابة الثمودية: ما نعرفه وما لا ندّعيه.
 *
 * ══════════════════════════════════════════════════════════════════════
 *  لماذا لا يقرأ النظام الحروف من الصخر تلقائيًّا
 * ══════════════════════════════════════════════════════════════════════
 * التعرّف على اللوحة شيء، وقراءة حروفها شيءٌ آخر. فالثاني يحتاج:
 *
 *   • عزلَ كلّ حرفٍ عن الصخرة المتآكلة — ولا بيانات مُعنونة لتدريب ذلك
 *   • تحديدَ اتّجاه الكتابة، وهو متقلّب: يمينًا، أو بالتناوب سطرًا سطرًا
 *     (boustrophedon)، أو رأسيًّا، أو دائريًّا حول النقش
 *   • فصلَ الكلمات — ولا فواصل بينها في الغالب
 *   • والحروف صوامتُ بلا حركات، فالكلمة الواحدة تحتمل قراءاتٍ عدّة
 *
 * ولو خمّن النظام نصًّا عربيًّا «معقول الشكل» لكان ذلك اختلاقًا: نصٌّ
 * يبدو صحيحًا ولا أصل له. وأمام لجنةٍ فيها من يقرأ الخطّ، ذاك أسوأ من
 * الصمت بكثير.
 *
 * ── فما الذي نفعله بدل ذلك ────────────────────────────────────────────
 * نفعل ما يفعله من يقرأ الخطّ فعلًا: نتعرّف على اللوحة، ثم نعرض قراءتها
 * الموثّقة إن وُجدت، ونضع بين يدي الزائر جدولَ الحروف ليطابقها بنفسه.
 *
 * المصدر: لوحة «أشكال حروف جبة الثمودية» من هيئة تطوير منطقة حائل.
 */

